/**
 * Regenerates src/components/diagrams/<code>/index.ts from the diagram files
 * on disk (see scripts/diagram-scan.ts). Usage: npm run diagrams:gen
 * The output depends only on the files present, so running it twice, or from
 * two places at once, gives the same result.
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { DIAGRAM_ROOT, scanDiagrams } from './diagram-scan';

export function registrySource(code: string, entries: { key: string; name: string }[]): string {
  const ident = (name: string) =>
    name
      .split('-')
      .map((p) => (/^\d/.test(p) ? `_${p}` : p.charAt(0).toUpperCase() + p.slice(1)))
      .join('');
  const sorted = [...entries].sort((a, b) => a.key.localeCompare(b.key));
  const lines = [
    '// Generated by `npm run diagrams:gen` from the files in this folder. Do not edit by hand.',
    "import type { DiagramRegistry } from '../types';",
    ...[...sorted].sort((a, b) => a.name.localeCompare(b.name)).map((e) => `import ${ident(e.name)} from './${e.name}';`),
    '',
    `/** Diagrams for ${code} lessons. Keys are referenced from lesson YAML (\`diagram: <key>\`). */`,
    'export const diagrams: DiagramRegistry = {',
    ...sorted.map((e) => `  '${e.key}': ${ident(e.name)},`),
    '};',
    '',
  ];
  return lines.join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename);
if (isMain) {
  const { files, problems } = scanDiagrams();
  for (const p of problems) console.error(`ERROR ${p}`);
  for (const code of ['9709', '9618', '9702', '9701']) {
    const out = path.join(DIAGRAM_ROOT, code, 'index.ts');
    const src = registrySource(
      code,
      files.filter((f) => f.code === code),
    );
    if (!existsSync(out) || readFileSync(out, 'utf8') !== src) writeFileSync(out, src);
  }
  console.log(`${files.length} diagrams registered`);
  process.exit(problems.length ? 1 : 0);
}
